// main.js — 메인 페이지 전용 기능 (메인 배너 클릭 효과)
// 최종 요구사항
// -> 상단 배너 클릭시
// 상단 메뉴 배경색을 변경하고
// 상단 메뉴는 360도 회전함
// 트랜지션으로 애니메이션 2초간 되게함

// 대상선정:
// 1. 이벤트 대상 : 상단배너 (.main-visual-img)
let 너를클릭해 = document.querySelector('.main-visual-img');
// 2. 변경대상 : 상단영역 (.top-area)
let 나야나 = document.querySelector('.top-area');

// 메인 배너와 상단영역이 있는 페이지(=메인 페이지)에서만 실행!
if (너를클릭해 && 나야나) {
  console.log('나는 누구인가?', 나야나);

  // const 는 상수 또는 함수를 담는 변수선언
  const 나야나함수 = (색상) => {
    console.log('함수호출! 전달값은?', 색상);
    // 상단요소의 배경색 바꾸기
    나야나.style.backgroundColor = 색상;
    나야나.style.transition = '2s ease-in-out';
    // 회전은 로고가 하도록 변경
    let 로고 = 나야나.querySelector('.logo-box');
    if (로고) {
      로고.style.rotate = '360deg';
      // 로고 트랜지션 : 2초후 1초간 ease-in-out
      로고.style.transition = '1s ease-in-out 2s';
    }
  }; ///////// 나야나함수 /////////

  // 3. 이벤트 설정하기 : 클릭이벤트
  // 클릭시 함수호출은 바로실행 안되게 화살표함수로 표시
  너를클릭해.onclick = () => {
    // 해당요소에 클릭이벤트가 발생하면 이 구역을 실행함
    나야나함수('orange');
  }; ///// onclick 함수 ///////
}


// ============================================================
// place 영역 배경 슬라이드 (바닐라JS)
// - 처음엔 1번 이미지 -> 2초 대기 -> 1초간 오른쪽에서 다음 이미지 등장
// - 한 바퀴 돌면 처음 이미지가 다시 오른쪽에서 들어옴 (무한 반복)
// 원리: 트랙을 -100% 이동 -> 끝나면 맨 앞 박스를 맨 뒤로 보내고
//       트랜지션 없이 위치를 0으로 되돌림 (사용자 눈엔 끊김 없음)
// ============================================================

// (()=>{코드})() -> 변수명 중복 위험을 없애준다!
// 이 구역은 바로 실행됨! 중괄호안이 지역변수가 됨!
// 전역변수는 함수바깥에 있는 변수
// 지역변수는 함수내부에 있느 변수
// 아래처럼 쓰고 중괄호안에 코드를 넣으면 된다!
/* (()=>{
        내코드...

})();
 */

const 플레이스트랙 = document.querySelector('.place-track');

if (플레이스트랙) {
  const 대기시간 = 2000; // 2초 후 이동 시작
  const 이동시간 = 1000; // 1초간 이동

  const 다음슬라이드 = () => {
    // 1) 1초간 왼쪽으로 한 칸 이동 (= 다음 이미지가 오른쪽에서 들어옴)
    플레이스트랙.style.transition = `transform ${이동시간}ms ease-in-out`;
    플레이스트랙.style.transform = 'translateX(-100%)';

    // 2) 이동이 끝나면 맨 앞 박스를 맨 뒤로 보내고 위치 초기화
    setTimeout(() => {
      플레이스트랙.style.transition = 'none';
      플레이스트랙.appendChild(플레이스트랙.firstElementChild);
      플레이스트랙.style.transform = 'translateX(0)';
      // 강제 리플로우 : 초기화가 트랜지션 없이 적용되도록
      void 플레이스트랙.offsetWidth;

      // 3) 2초 대기 후 다시 반복
      setTimeout(다음슬라이드, 대기시간);
    }, 이동시간);
  }; ///////// 다음슬라이드 /////////

  // 최초 : 첫번째 이미지가 2초간 보인 후 시작
  setTimeout(다음슬라이드, 대기시간);
}